/** Run bun scripts/card-silhouette.ts to generate the loading outline. */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import polygonClipping, { type MultiPolygon, type Polygon } from 'polygon-clipping';
import { BufferAttribute, BufferGeometry, Group, Mesh, PerspectiveCamera, Vector3 } from 'three';
import { CAMERA_DISTANCE, CAMERA_FOV, CARD_ROTATION_X, START_SCALE } from '../src/lib/layout.ts';

const GLB = new URL('../src/lib/assets/card.glb', import.meta.url);
const OUT = new URL('../src/lib/cardSilhouette.ts', import.meta.url);
const UNITS = 1000;

export async function computeSilhouette(glb: Uint8Array): Promise<string> {
	const doc = await new NodeIO().registerExtensions(ALL_EXTENSIONS).readBinary(glb);

	// Same hierarchy as Scene.svelte and Card.svelte
	const scaled = new Group();
	scaled.scale.setScalar(START_SCALE);
	const rotated = new Group();
	rotated.rotation.set(CARD_ROTATION_X, 0, 0);
	scaled.add(rotated);

	for (const mesh of doc.getRoot().listMeshes()) {
		for (const primitive of mesh.listPrimitives()) {
			const position = primitive.getAttribute('POSITION')?.getArray();
			const indices = primitive.getIndices()?.getArray();
			if (!position || !indices) throw new Error('Card primitive without positions or indices');
			const geometry = new BufferGeometry();
			geometry.setAttribute('position', new BufferAttribute(Float32Array.from(position), 3));
			geometry.setIndex(Array.from(indices));
			// Card.svelte centres each face's thickness on the origin
			geometry.computeBoundingBox();
			const box = geometry.boundingBox;
			if (!box) throw new Error('No bounding box');
			geometry.translate(0, 0, -(box.max.z + box.min.z) / 2);
			rotated.add(new Mesh(geometry));
		}
	}
	scaled.updateMatrixWorld(true);

	const camera = new PerspectiveCamera(CAMERA_FOV, 1);
	camera.position.set(0, 0, CAMERA_DISTANCE);
	camera.lookAt(0, 0, 0);
	camera.updateMatrixWorld(true);

	// With aspect 1, NDC x and y are both in half canvas heights
	const project = (v: Vector3): [number, number] => {
		v.project(camera);
		return [(v.x * UNITS) / 2, (-v.y * UNITS) / 2];
	};

	const triangles: Polygon[] = [];
	const v = new Vector3();
	rotated.traverse((child) => {
		if (!(child instanceof Mesh)) return;
		const geometry = child.geometry as BufferGeometry;
		const position = geometry.getAttribute('position');
		const index = geometry.getIndex();
		if (!index) return;
		for (let i = 0; i < index.count; i += 3) {
			const corner = (k: number) =>
				project(v.fromBufferAttribute(position, index.getX(i + k)).applyMatrix4(child.matrixWorld));
			const a = corner(0);
			const b = corner(1);
			const c = corner(2);

			if (Math.abs((b[0] - a[0]) * (c[1] - a[1]) - (c[0] - a[0]) * (b[1] - a[1])) < 1e-9) continue;
			triangles.push([[a, b, c, a]]);
		}
	});

	const union: MultiPolygon = polygonClipping.union(triangles[0] ?? [], ...triangles.slice(1));
	return union
		.flatMap((polygon) =>
			polygon.map(
				(ring) =>
					'M' +
					ring
						.slice(0, -1)
						.map(([x, y]) => `${x.toFixed(3)} ${y.toFixed(3)}`)
						.join('L') +
					'Z'
			)
		)
		.join('');
}

export function silhouetteModule(path: string): string {
	const numbers = (path.match(/-?\d+(?:\.\d+)?/g) ?? []).map(Number);
	const xs = numbers.filter((_, i) => i % 2 === 0);
	const ys = numbers.filter((_, i) => i % 2 === 1);
	const bounds = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
	return `// Generated by scripts/card-silhouette.ts from card.glb and layout.ts. Do not edit.
// Coordinates are in thousandths of canvas height relative to its centre.
export const CARD_SILHOUETTE = '${path}';
// [left, top, right, bottom] of the outline, in the same units
export const CARD_BOUNDS = [${bounds.map((v) => v.toFixed(3)).join(', ')}] as const;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const path = await computeSilhouette(new Uint8Array(await readFile(GLB)));
	await writeFile(OUT, silhouetteModule(path));
	console.log(`Wrote ${OUT.pathname} (${String(path.length)} characters)`);
}
